-- Run after 20261106_link_item_poster.sql and profile privacy migrations.
-- Additive migration: existing collection records are preserved.
begin;
alter table public.items drop constraint if exists items_category_check;
-- Do not rewrite legacy genre-valued categories (e.g. Roman, Tarih).
-- NOT VALID preserves existing rows but still checks every new INSERT/UPDATE.
-- Legacy rows must be classified separately before editing or validating them.
alter table public.items add constraint items_category_check check(category in ('kitap','film','dizi','muzik')) not valid;
do $$
begin
  if not exists(select 1 from public.items where category not in ('kitap','film','dizi','muzik')) then
    alter table public.items validate constraint items_category_check;
  else
    raise notice 'Eski kategori değerleri korundu. Bu kayıtları düzenlemeden önce içerik türlerini ayrıca doğrulayın.';
  end if;
end;
$$;
alter table public.items add column if not exists music_recording_id uuid;
alter table public.items add column if not exists music_release_id uuid;
alter table public.items add column if not exists album text;
alter table public.items add column if not exists duration_ms integer;
alter table public.items add column if not exists youtube_id text;
create unique index if not exists items_music_recording_unique on public.items(user_id,music_recording_id) where music_recording_id is not null;
create or replace function collection_private.guard_music_fields()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.music_recording_id is not null and new.category <> 'muzik' then raise exception 'Geçersiz müzik kategorisi.'; end if;
  if TG_OP='UPDATE' and old.music_recording_id is not null and new.music_recording_id is distinct from old.music_recording_id then raise exception 'Şarkının kaynak kimliği değiştirilemez.'; end if;
  if new.youtube_id is not null and new.youtube_id !~ '^[A-Za-z0-9_-]{11}$' then raise exception 'Geçersiz video.'; end if;
  if char_length(new.album)>500 or new.duration_ms<0 then raise exception 'Geçersiz şarkı bilgisi.'; end if;
  return new;
end;
$$;
drop trigger if exists guard_music_fields on public.items;
create trigger guard_music_fields before insert or update on public.items for each row execute function collection_private.guard_music_fields();
-- Metadata is verified by the server; browser roles cannot forge provider identifiers.
revoke insert(music_recording_id,music_release_id,album,duration_ms,youtube_id), update(music_recording_id,music_release_id,album,duration_ms,youtube_id) on public.items from public,anon,authenticated;
grant select,insert,update,delete on public.items to service_role;

create table if not exists public.music_playlists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  name text not null check(char_length(btrim(name)) between 1 and 100),
  created_at timestamptz not null default now()
);
create table if not exists public.music_playlist_items (
  playlist_id bigint not null references public.music_playlists(id) on delete cascade,
  item_id bigint not null references public.items(id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key(playlist_id,item_id)
);
create index if not exists music_playlists_owner on public.music_playlists(user_id);
create index if not exists music_playlist_items_item on public.music_playlist_items(item_id);
alter table public.music_playlists enable row level security;
alter table public.music_playlist_items enable row level security;
revoke all on public.music_playlists,public.music_playlist_items from public,anon,authenticated;
grant select,delete on public.music_playlists,public.music_playlist_items to authenticated;
grant insert(user_id,name),update(name) on public.music_playlists to authenticated;
grant insert(playlist_id,item_id) on public.music_playlist_items to authenticated;
grant usage on sequence public.music_playlists_id_seq to authenticated;
drop policy if exists playlist_read on public.music_playlists;
create policy playlist_read on public.music_playlists for select to authenticated using (
  user_id=auth.uid() or exists(select 1 from public.profiles p where p.id=user_id and p.is_public)
  or exists(select 1 from public.friendships f where f.status='accepted' and
    ((f.requester_id=auth.uid() and f.recipient_id=user_id) or (f.recipient_id=auth.uid() and f.requester_id=user_id)))
);
drop policy if exists playlist_insert on public.music_playlists;
create policy playlist_insert on public.music_playlists for insert to authenticated with check(user_id=auth.uid());
drop policy if exists playlist_update on public.music_playlists;
create policy playlist_update on public.music_playlists for update to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
drop policy if exists playlist_delete on public.music_playlists;
create policy playlist_delete on public.music_playlists for delete to authenticated using(user_id=auth.uid());
drop policy if exists playlist_items_read on public.music_playlist_items;
create policy playlist_items_read on public.music_playlist_items for select to authenticated using (
  exists(select 1 from public.music_playlists p where p.id=playlist_id) and exists(select 1 from public.items i where i.id=item_id)
);
drop policy if exists playlist_items_insert on public.music_playlist_items;
create policy playlist_items_insert on public.music_playlist_items for insert to authenticated with check (
  exists(select 1 from public.music_playlists p where p.id=playlist_id and p.user_id=auth.uid())
  and exists(select 1 from public.items i where i.id=item_id and i.user_id=auth.uid() and i.category='muzik')
);
drop policy if exists playlist_items_delete on public.music_playlist_items;
create policy playlist_items_delete on public.music_playlist_items for delete to authenticated using (
  exists(select 1 from public.music_playlists p where p.id=playlist_id and p.user_id=auth.uid())
);
notify pgrst,'reload schema';
commit;
