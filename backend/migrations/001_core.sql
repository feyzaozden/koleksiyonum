-- Independent PostgreSQL only. No Supabase schemas or live data imports.
CREATE SCHEMA accounts;
CREATE SCHEMA collection;
REVOKE ALL ON SCHEMA accounts, collection FROM PUBLIC;

CREATE TABLE accounts.users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL CHECK (email = btrim(email) AND position('@' in email) > 1),
  password_hash text,
  email_verified_at timestamptz,
  disabled_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_unique ON accounts.users(lower(email));
-- NULL password_hash permits staged imports; login must reject NULL hashes.
CREATE TABLE collection.profiles (
  id uuid PRIMARY KEY REFERENCES accounts.users(id) ON DELETE CASCADE,
  username text NOT NULL CHECK (username ~ '^[a-z][a-z0-9_.]{2,19}$'),
  display_name text NOT NULL,
  bio text NOT NULL DEFAULT '',
  avatar_emoji text NOT NULL DEFAULT '📖',
  avatar_path text,
  is_public boolean NOT NULL DEFAULT false,
  music_description text NOT NULL DEFAULT '',
  music_cover_path text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(username)
);
CREATE TABLE collection.items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES accounts.users(id) ON DELETE CASCADE,
  category text NOT NULL CHECK(category IN ('kitap','film','dizi','muzik')),
  title text NOT NULL CHECK(length(btrim(title))>0),
  creator text, year text,
  status text NOT NULL DEFAULT 'bekliyor' CHECK(status IN ('bekliyor','devam','bitti')),
  note text, start_date date, end_date date,
  rating smallint CHECK(rating BETWEEN 1 AND 10), emoji text,
  added_at timestamptz NOT NULL DEFAULT now(),
  progress jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(progress)='object'),
  source text, source_id bigint, dedupe_key text, poster_path text,
  music_recording_id uuid, music_release_id uuid, album text,
  duration_ms integer CHECK(duration_ms>=0),
  youtube_id text CHECK(youtube_id ~ '^[A-Za-z0-9_-]{11}$'),
  youtube_source_id text CHECK(youtube_source_id ~ '^[A-Za-z0-9_-]{11}$'),
  featured_at timestamptz,
  CHECK(end_date IS NULL OR start_date IS NULL OR end_date>=start_date),
  CHECK(music_recording_id IS NULL OR category='muzik'),
  CHECK(youtube_source_id IS NULL OR (category='muzik' AND music_recording_id IS NULL))
);
CREATE INDEX items_owner_category ON collection.items(user_id,category,added_at DESC);
CREATE UNIQUE INDEX items_identity_unique ON collection.items(user_id,category,dedupe_key) WHERE dedupe_key IS NOT NULL;
CREATE UNIQUE INDEX items_source_unique ON collection.items(user_id,category,source,source_id) WHERE source_id IS NOT NULL;
CREATE UNIQUE INDEX items_music_unique ON collection.items(user_id,music_recording_id) WHERE music_recording_id IS NOT NULL;
CREATE UNIQUE INDEX items_youtube_unique ON collection.items(user_id,youtube_source_id) WHERE youtube_source_id IS NOT NULL;
CREATE INDEX items_favorites ON collection.items(user_id,featured_at) WHERE featured_at IS NOT NULL;

CREATE TABLE collection.friendships (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  requester_id uuid NOT NULL REFERENCES collection.profiles(id) ON DELETE CASCADE,
  recipient_id uuid NOT NULL REFERENCES collection.profiles(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','accepted')),
  created_at timestamptz NOT NULL DEFAULT now(),
  accepted_at timestamptz,
  CHECK(requester_id<>recipient_id)
);
CREATE UNIQUE INDEX friendship_pair_unique ON collection.friendships(least(requester_id,recipient_id),greatest(requester_id,recipient_id));
CREATE INDEX friendships_recipient ON collection.friendships(recipient_id);
CREATE INDEX friendships_requester ON collection.friendships(requester_id);

-- Default deny. Grant narrowly only after authenticated API authorization exists.
REVOKE ALL ON ALL TABLES IN SCHEMA accounts,collection FROM PUBLIC,collection_app;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA accounts,collection FROM PUBLIC,collection_app;
ALTER TABLE accounts.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE collection.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE collection.items ENABLE ROW LEVEL SECURITY;
ALTER TABLE collection.friendships ENABLE ROW LEVEL SECURITY;
